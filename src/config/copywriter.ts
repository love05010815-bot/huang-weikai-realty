    "",
    "🔴 字數是硬要求，不是參考值：每一版都要達到該版的字數下限，不到下限就是不合格；寧可接近上限。字數以中文字計、不含空白。",
    "",
    "內容深度（每一版都要有，只是長短不同）：",
    "1. 這是什麼事、什麼時候開始（用原文的日期與機構名）",
    "2. 為什麼跟正在看房、換屋或租屋的人有關 —— 講到讀者身上，不要停在政策層次",
    "3. 至少一組原文的數字，並換算成讀者有感的說法（例如「以總價 1,500 萬來算差 150 萬」）",
    "4. 注意事項或常見誤解（例如「上限 7 成不代表每個人都貸得到 7 成」）",
    "5. 下一步：讀者現在可以做什麼",
    "",
    "可以用一般性的房產常識把名詞、原理與影響解釋清楚（例如什麼是貸款成數、為什麼成數會影響自備款），這不算新增資料；",
    "但**數字、地名、機構名、日期、人名只能用原文出現的**，一個都不能自己補、不能推估。",
    "",
    "輸出格式（照這個順序；每個版本用「## 版本名」當標題，後台靠這個字切段，不要改字、不要加別的字）：",
