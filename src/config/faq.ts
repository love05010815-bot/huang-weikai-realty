/** 答案攤平成純文字，給 FAQPage JSON-LD 用（Google 讀的那份，不含連結） */
export function faqAnswerText(item: FaqItem): string {
  const steps = item.steps.map((s, i) => `${i + 1}. ${s.title}：${s.text}`).join(" ");
  return `${item.intro} ${steps} ${item.costs}`;
}
